#!/usr/bin/env python3
"""Generate edition-scoped PDF2 dictionary objects from the reviewed source catalogue.

Base table coverage and explicitly selected EC3 overrides do not imply complete
algorithmic, conditional, semantic or document-profile conformance.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re

from generate_specification import nullable_string, php_bool, php_string, value_classes
from generate_semantic_rules import load_rules, render_rules

MARKER = '// Generated by tools/generate_iso32000_2.py; edit the reviewed catalogue or generator.'
HEADER = '<?php\n\n' + MARKER + '\n\ndeclare(strict_types=1);\n\n'
NAMESPACE = 'PDF\\Specification\\Iso32000_2'


def generate(root: Path, check: bool = False) -> None:
    catalogue = root / 'resources' / 'iso32000-2-2020'
    metadata = json.loads((catalogue / 'metadata.json').read_text(encoding='utf-8'))
    tables = json.loads((catalogue / 'dictionaries.json').read_text(encoding='utf-8'))
    semantic_rules = load_rules(catalogue)
    files = []
    differences = []
    classes = []

    def save(path: Path, content: str) -> None:
        expected = content.encode('utf-8')
        if check:
            if not path.is_file() or path.read_bytes() != expected:
                differences.append(str(path.relative_to(root)))
        elif not path.is_file() or path.read_bytes() != expected:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(expected)

    def source(table: dict, page: int) -> str:
        edition = 'new SourceEdition(' + ', '.join([
            php_string(metadata['edition_identifier']), php_string(metadata['standard']),
            php_string(metadata['specified_pdf_version']), php_string(metadata['family']),
            'new ErrataCollection(' + str(metadata['errata_collection']['number']) + ', ' + php_string(metadata['errata_collection']['publication_date']) + ')',
        ]) + ')'
        original = metadata['source']
        return 'new SourceReference(' + ', '.join([
            php_string(table['id']), nullable_string(table['section']), str(page),
            php_string(metadata['standard']), php_string(original['sha256']),
            php_string(original['document']), edition,
        ]) + ')'

    for table in tables:
        name = table['name']
        definition_name = name + 'Definition'
        definition = HEADER + 'namespace ' + NAMESPACE + '\\Definition;\n\n'
        imports = ['EntryDefinition', 'ErrataCollection', 'ErrataResolution', 'ErrataReviewStatus', 'ObjectTypeConstraint', 'Requirement', 'SourceEdition', 'SourceReference', 'TableDefinition']
        if any(entry.get('allowed_names') for entry in table['entries']):
            imports.append('NameAlternatives')
        definition += '\n'.join('use PDF\\Specification\\' + item + ';' for item in imports) + '\n'
        if 'NameAlternatives' in imports:
            definition += 'use PDF\\Syntax\\Object\\NameType;\n'
        definition += '\n'
        definition += '/** ISO 32000-2:2020 source table ' + table['id'] + '; explicitly reviewed EC3 constraints remain separate. */\n'
        definition += 'final readonly class ' + definition_name + ' extends TableDefinition\n{\n    public function __construct()\n    {\n        parent::__construct(\n            ' + source(table, table['pdf_pages'][0]) + ',\n            ' + php_string(table['title']) + ',\n            [\n'
        generated_entries = []
        fixed_names = [entry['name'].lower() for entry in table['entries']]
        all_entries = [(entry, False) for entry in table['entries']] + [(entry, True) for entry in table.get('variable_entries', [])]
        for index, (entry, variable) in enumerate(all_entries):
            requirement = entry.get('qualifier') or (('Required' if entry['required'] else 'Optional') + ('; conditional' if entry['conditional'] else ''))
            if entry['deprecated_in'] and not re.search(r'deprecated\s+in\s+PDF', requirement, re.I):
                requirement += '; deprecated in PDF ' + entry['deprecated_in']
            constraint = 'new ObjectTypeConstraint(' + ', '.join([
                php_string(entry['type']), 'indirect: ' + php_bool(entry['indirect']),
                'direct: ' + php_bool(entry['direct']), 'fixedName: ' + nullable_string(entry['fixed_name']),
            ])
            if entry.get('array_elements_direct'):
                constraint += ', directArrayElements: true'
            if entry.get('array_elements_indirect'):
                constraint += ', indirectArrayElements: true'
            if entry.get('array_member_type'):
                constraint += ', arrayElementConstraint: new ObjectTypeConstraint(' + php_string(entry['array_member_type']) + ')'
            if entry.get('allowed_names'):
                constraint += ', nameAlternatives: new NameAlternatives(' + ', '.join('new NameType(' + php_string(name) + ')' for name in entry['allowed_names']) + ')'
            if entry.get('array_length') is not None:
                constraint += ', arrayLength: ' + str(entry['array_length'])
            constraint += ')'
            arguments = [php_string(entry['name']), constraint,
                'new Requirement(' + ', '.join([php_string(requirement), php_bool(entry['required']), php_bool(entry['conditional']), php_bool(entry.get('inheritable', False)), nullable_string(entry['introduced_in'])]) + ')',
                source(table, entry['pdf_page']), php_string(entry['description'])]
            if variable:
                arguments += ['variable: true']
            if entry['errata']:
                errata = entry['errata']
                arguments += ['errata: new ErrataResolution(' + ', '.join([
                    php_string(errata['id']), str(errata['pdf_page']), 'ErrataReviewStatus::' + errata['review_status'],
                    'issueNumber: ' + ('null' if errata['issue_number'] is None else str(errata['issue_number'])),
                    'annotationName: ' + nullable_string(errata['annotation_name']),
                ]) + ')']
            definition += '                new EntryDefinition(' + ', '.join(arguments) + '),\n'
            entry_name = 'NamedEntry' + str(index - len(table['entries']) + 1) if variable else ('Key' if entry['name'][0].isdigit() else '') + entry['name'].replace('.', '_').replace('-', '_') + 'Entry'
            if not variable and fixed_names.count(entry['name'].lower()) > 1:
                entry_name += 'Name' + entry['name'].encode('ascii').hex().upper()
            types = value_classes(entry)
            entry_php = HEADER + 'namespace ' + NAMESPACE + '\\Dictionary\\' + name + ';\n\nuse ' + NAMESPACE + '\\Definition\\' + definition_name + ';\n'
            for item in sorted(set(types + (['NameType'] if variable else []))):
                entry_php += 'use PDF\\Syntax\\' + ('FileStructure' if item == 'BasicType' else 'Object') + '\\' + item + ';\n'
            entry_php += '\n/** ISO 32000-2:2020 EC3, table ' + table['id'] + ', /' + entry['name'] + '. */\nfinal class ' + entry_name + ' extends \\PDF\\Specification\\SchemaEntry\n{\n    public const string TABLE = ' + php_string(table['id']) + ';\n    public const string KEY = ' + php_string(entry['name']) + ';\n'
            if variable:
                entry_php += '    public const bool VARIABLE = true;\n'
            entry_php += '\n    public function __construct(' + ('NameType $key, ' if variable else '') + '|'.join(types) + ' $value)\n    {\n        parent::__construct((new ' + definition_name + '())->' + ('variableEntry' if variable else 'entry') + '(' + php_string(entry['name']) + '), $value' + (', $key' if variable else '') + ');\n    }\n}\n'
            path = root / 'src' / 'Specification' / 'Iso32000_2' / 'Dictionary' / name / (entry_name + '.php')
            save(path, entry_php)
            files.append(path.relative_to(root).as_posix())
            generated_entries.append({'name': entry['name'], 'variable': variable, 'class': NAMESPACE + '\\Dictionary\\' + name + '\\' + entry_name})
        common = table.get('common_tables', [])
        common_names = [next(item['name'] for item in tables if item['id'] == identifier) + 'Definition' for identifier in common]
        definition += '            ],\n            [' + ', '.join('new ' + name + '()' for name in common_names) + '],\n'
        definition += render_rules(semantic_rules.get(table['id'], []), lambda page: source(table, page))
        definition += '        );\n    }\n}\n'
        path = root / 'src' / 'Specification' / 'Iso32000_2' / 'Definition' / (definition_name + '.php')
        save(path, definition)
        files.append(path.relative_to(root).as_posix())
        dictionary = HEADER + 'namespace ' + NAMESPACE + '\\Dictionary;\n\nuse ' + NAMESPACE + '\\Definition\\' + definition_name + ';\nuse PDF\\Specification\\SchemaDictionary;\nuse PDF\\Syntax\\Object\\DictionaryObject\\Entry;\n\n/** ISO 32000-2:2020 EC3, table ' + table['id'] + '. */\nfinal class ' + name + ' extends SchemaDictionary\n{\n    public const string TABLE = ' + php_string(table['id']) + ';\n    public const array COMMON_TABLES = [' + ', '.join(php_string(identifier) for identifier in common) + '];\n\n    public function __construct(Entry ...$entries)\n    {\n        parent::__construct(new ' + definition_name + '(), ...$entries);\n    }\n}\n'
        path = root / 'src' / 'Specification' / 'Iso32000_2' / 'Dictionary' / (name + '.php')
        save(path, dictionary)
        files.append(path.relative_to(root).as_posix())
        classes.append({'table': table['id'], 'title': table['title'], 'class': NAMESPACE + '\\Dictionary\\' + name, 'definition_class': NAMESPACE + '\\Definition\\' + definition_name, 'common_tables': common, 'entries': generated_entries})
    aggregation = HEADER + 'namespace ' + NAMESPACE + ';\n\nuse PDF\\Specification\\Catalogue as SpecificationCatalogue;\nuse PDF\\Specification\\TableDefinition;\n\n/** Explicit immutable edition-scoped aggregation; no global registry or runtime source I/O. */\nfinal readonly class Catalogue\n{\n    private SpecificationCatalogue $catalogue;\n\n    public function __construct()\n    {\n        $this->catalogue = new SpecificationCatalogue(\n'
    aggregation += ''.join('            new \\' + item['definition_class'] + '(),\n' for item in classes)
    aggregation += '        );\n    }\n\n    public function dictionary(string $table): TableDefinition\n    {\n        return $this->catalogue->dictionary($table);\n    }\n\n    /** @return iterable<TableDefinition> */\n    public function definitions(): iterable\n    {\n        yield from $this->catalogue->definitions();\n    }\n}\n'
    aggregation_path = root / 'src' / 'Specification' / 'Iso32000_2' / 'Catalogue.php'
    save(aggregation_path, aggregation)
    files.append(aggregation_path.relative_to(root).as_posix())
    wanted = {(root / file).resolve() for file in files}
    for path in (root / 'src' / 'Specification' / 'Iso32000_2').rglob('*.php'):
        if path.resolve() not in wanted and path.read_text(encoding='utf-8').startswith('<?php\n\n' + MARKER):
            # Check-only stale reporting; preserve authored files.
            differences.append(str(path.relative_to(root)) + ' (stale generated file)')
    save(catalogue / 'classes.json', json.dumps(classes, ensure_ascii=False, indent=2) + '\n')
    save(catalogue / 'generated-files.json', json.dumps(files, indent=2) + '\n')
    if differences:
        raise SystemExit('\n'.join(differences))
    print(f'ISO 32000-2 catalogue: {len(tables)} dictionary definitions, {sum(len(t["entries"]) + len(t.get("variable_entries", [])) for t in tables)} entries, {len(files)} reproducible PHP files.')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generate(args.root, args.check)
