#!/usr/bin/env python3
"""Generate explicit Adobe supplement dictionaries and immutable definitions.

Uses the retained source inventory, with separate Adobe and ISO provenance.
There are no global PHP registries or factories: every definition and dictionary
is an object whose constructor explicitly constructs its base definitions.
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

from generate_specification import TYPE_MAP, class_name, nullable_string, php_bool, php_string

MARKER = '// Generated by tools/generate_adobe_supplement.py; edit the catalogue or generator.'
HEADER = '<?php\n\n' + MARKER + '\n\ndeclare(strict_types=1);\n\n'


def constraint_type(entry: dict) -> str:
    if entry.get('validation_type'):
        return entry['validation_type']
    return {'date string': 'date', 'various': '(various)', 'text string or array of text string': 'text string or array of text strings'}.get(entry['type'], entry['type'])


def value_classes(entry: dict) -> list[str]:
    type_name = constraint_type(entry).lower().strip(' ‘’')
    if type_name in ['(any)', '(various)', '(undefined)', 'any']:
        classes = ['BasicType']
    else:
        classes = []
        for part in re.split(r'\s*,\s*(?:or\s+)?|\s+or\s+', type_name):
            if part.startswith('array of '):
                classes.append('ArrayType')
            elif part in TYPE_MAP:
                classes.extend(TYPE_MAP[part])
            else:
                raise ValueError('Unmapped PDF object type: ' + type_name)
    classes = [] if entry['indirect'] else [item for item in classes if item != 'StreamObject']
    return list(dict.fromkeys(classes if entry['direct'] else [*classes, 'IndirectReference']))


def source_expression(table: dict, page: int, metadata: dict) -> str:
    return 'new SourceReference(' + ', '.join([
        php_string(table['id']), nullable_string(table['section']), str(page),
        php_string(metadata['standard']), php_string(metadata['document_sha256']),
        php_string(metadata['document']),
    ]) + ')'


def entry_expression(table: dict, entry: dict, variable: bool, metadata: dict) -> str:
    array_member_constraint = 'new ObjectTypeConstraint(' + php_string(entry['array_member_validation_type']) + ')' if entry.get('array_member_validation_type') else 'null'
    constraint = 'new ObjectTypeConstraint(' + ', '.join([
        php_string(constraint_type(entry)), php_bool(entry['indirect']), php_bool(entry['direct']),
        php_bool(entry['array_elements_direct']), nullable_string(entry['fixed_name']), php_bool(entry['array_elements_indirect']),
        array_member_constraint,
    ]) + ')'
    requirement = 'new Requirement(' + ', '.join([
        nullable_string(entry['qualifier']), php_bool(entry['required']), php_bool(entry['conditional']),
        php_bool(entry['inheritable']), nullable_string(entry['introduced_in']),
    ]) + ')'
    arguments = [php_string(entry['name']), constraint, requirement, source_expression(table, entry['pdf_page'], metadata), php_string(entry['description']), php_bool(variable)]
    if entry.get('implementation_correction'):
        correction = entry['implementation_correction']
        arguments.append('new \\PDF\\Specification\\ImplementationCorrection(' + ', '.join(php_string(correction[key]) for key in ['id', 'rationale', 'evidence_url', 'evidence_locator']) + ')')
    return 'new EntryDefinition(' + ', '.join(arguments) + ')'


def generate(root: Path, check: bool = False) -> None:
    catalogue_path = root / 'resources' / 'adobe-supplement-iso32000'
    tables = json.loads((catalogue_path / 'dictionaries.json').read_text(encoding='utf-8'))
    metadata = json.loads((catalogue_path / 'metadata.json').read_text(encoding='utf-8'))
    iso_classes = {item['table']: item['definition_class'] for item in json.loads((root / 'resources' / 'iso32000-1' / 'classes.json').read_text(encoding='utf-8'))}
    adobe_names = {table['id']: class_name(table['title'].replace('Additional entries specific in a ', 'Entries in a ').replace('Additional entries to a ', 'Entries in a '), table['id']) for table in tables}
    output = root / 'src' / 'Specification' / 'Adobe'
    differences = []
    files = []
    classes = []

    def save(path: Path, content: str) -> None:
        expected = content.encode('utf-8')
        if check:
            if not path.is_file() or path.read_bytes() != expected:
                differences.append(str(path.relative_to(root)))
        elif not path.is_file() or path.read_bytes() != expected:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(expected)

    for table in tables:
        name = adobe_names[table['id']]
        definition_name = name + 'Definition'
        title = table['title'].replace('*/', '* /')
        common = [*table['iso_base_tables'], *table['adobe_base_tables']]
        php = HEADER + f'namespace PDF\\Specification\\Adobe\\Dictionary;\n\nuse PDF\\Specification\\Adobe\\Definition\\{definition_name};\nuse PDF\\Specification\\SchemaDictionary;\nuse PDF\\Syntax\\Object\\DictionaryObject\\Entry;\n\n'
        direct_extensions = table['id'] in ['3.25a', '3.25b']
        if direct_extensions:
            php = php.replace('use PDF\\Specification\\Adobe\\Definition\\', 'use PDF\\Document\\Extensions\\ExtensionDirectness;\nuse PDF\\Specification\\Adobe\\Definition\\', 1)
        php += f'/** Adobe 1.7 ExtensionLevel 3, table {table["id"]}: {title}. */\nfinal class {name} extends SchemaDictionary\n{{\n'
        php += f'    public const string TABLE = {php_string(table["id"])};\n    public const array COMMON_TABLES = [' + ', '.join(php_string(item) for item in common) + '];\n'
        php += f'\n    public function __construct(Entry ...$entries)\n    {{\n        parent::__construct(new {definition_name}(), ...$entries);\n'
        if direct_extensions:
            php += '        $this->validateExtensionEntries();\n'
        php += '    }\n'
        if direct_extensions:
            php += '\n    #[\\NoDiscard]\n    public function with(Entry $entry): static\n    {\n        $result = parent::with($entry);\n        $result->validateExtensionEntries();\n        return $result;\n    }\n'
            php += '\n    public function validate(): void\n    {\n        $this->validateExtensionEntries();\n        parent::validate();\n'
            if table['id'] == '3.25a':
                php += "        foreach ($this->entries() as $entry) {\n            if ($entry->key()->value !== 'Type') {\n                return;\n            }\n        }\n        throw new \\InvalidArgumentException('An extensions dictionary requires at least one developer prefix.');\n"
            php += '    }\n\n    private function validateExtensionEntries(): void\n    {\n        (new ExtensionDirectness())->validate($this);\n'
            if table['id'] == '3.25a':
                php += "        foreach ($this->entries() as $entry) {\n            if (!$this->definition()->has($entry->key())) {\n                $this->definition()->variableEntry('Prefix name')->type->validate($entry->value());\n            }\n        }\n"
            php += '    }\n'
        php += '}\n'
        path = output / 'Dictionary' / (name + '.php')
        save(path, php)
        files.append(path.relative_to(root).as_posix())
        php = HEADER + 'namespace PDF\\Specification\\Adobe\\Definition;\n\nuse PDF\\Specification\\EntryDefinition;\nuse PDF\\Specification\\ObjectTypeConstraint;\nuse PDF\\Specification\\Requirement;\nuse PDF\\Specification\\SourceReference;\nuse PDF\\Specification\\TableDefinition;\n\n'
        php += f'/** Adobe table {table["id"]}: {title}; ISO bases remain separately sourced. */\nfinal readonly class {definition_name} extends TableDefinition\n{{\n    public function __construct()\n    {{\n        parent::__construct(\n            {source_expression(table, table["pdf_pages"][0], metadata)},\n            {php_string(table["title"])},\n            [\n'
        for variable in [False, True]:
            for entry in table['variable_entries'] if variable else [*table['entries'], *table['prose_entries']]:
                php += '                ' + entry_expression(table, entry, variable, metadata) + ',\n'
        common_expressions = []
        for identifier in table['iso_base_tables']:
            if identifier not in iso_classes:
                raise ValueError(f'Missing ISO base {identifier} for Adobe table {table["id"]}')
            common_expressions.append('new \\' + iso_classes[identifier] + '()')
        for identifier in table['adobe_base_tables']:
            if identifier not in adobe_names:
                raise ValueError(f'Missing Adobe base {identifier} for {table["id"]}')
            common_expressions.append('new ' + adobe_names[identifier] + 'Definition()')
        php += '            ],\n            [' + ', '.join(common_expressions) + '],\n        );\n    }\n}\n'
        path = output / 'Definition' / (definition_name + '.php')
        save(path, php)
        files.append(path.relative_to(root).as_posix())
        generated_entries = []
        for variable in [False, True]:
            for index, entry in enumerate(table['variable_entries'] if variable else [*table['entries'], *table['prose_entries']]):
                key = entry['name']
                entry_name = ('NamedEntry' if index == 0 else f'NamedEntry{index + 1}') if variable else ('Key' if key[0].isdigit() else '') + key + 'Entry'
                entry_name = entry_name.replace('.', '_').replace('-', '_')
                types = value_classes(entry)
                imports = [f'use PDF\\Syntax\\FileStructure\\{item};' if item == 'BasicType' else f'use PDF\\Syntax\\Object\\{item};' for item in sorted(set(types + (['NameType'] if variable else [])))]
                php = HEADER + f'namespace PDF\\Specification\\Adobe\\Dictionary\\{name};\n\nuse PDF\\Specification\\Adobe\\Definition\\{definition_name};\n' + '\n'.join(imports) + '\n\n'
                qualifier = (entry['qualifier'] or 'Unspecified requirement').replace('*/', '* /')
                php += f'/** Adobe table {table["id"]}, /{key}; PDF type: {entry["type"]}; {qualifier}. */\nfinal class {entry_name} extends \\PDF\\Specification\\SchemaEntry\n{{\n    public const string TABLE = {php_string(table["id"])};\n    public const string KEY = {php_string(key)};\n'
                if variable:
                    php += '    public const bool VARIABLE = true;\n'
                arguments = ('NameType $key, ' if variable else '') + '|'.join(types) + ' $value'
                expression = f'(new {definition_name}())->' + ('variableEntry' if variable else 'entry') + '(' + php_string(key) + ')'
                php += f'\n    public function __construct({arguments})\n    {{\n        parent::__construct({expression}, $value' + (', $key' if variable else '') + ');\n    }\n}\n'
                path = output / 'Dictionary' / name / (entry_name + '.php')
                save(path, php)
                files.append(path.relative_to(root).as_posix())
                generated_entries.append({'name': key, 'variable': variable, 'class': f'PDF\\Specification\\Adobe\\Dictionary\\{name}\\{entry_name}'})
        classes.append({'table': table['id'], 'title': table['title'], 'class': f'PDF\\Specification\\Adobe\\Dictionary\\{name}', 'definition_class': f'PDF\\Specification\\Adobe\\Definition\\{definition_name}', 'iso_base_tables': table['iso_base_tables'], 'adobe_base_tables': table['adobe_base_tables'], 'common_tables': common, 'entries': generated_entries})
    wanted = {(root / file).resolve() for file in files}
    if output.exists():
        if not output.resolve().is_relative_to((root / 'src' / 'Specification').resolve()):
            raise ValueError('Output is outside Specification.')
        for file in output.rglob('*.php'):
            if file.resolve() not in wanted and file.read_text(encoding='utf-8').startswith('<?php\n\n' + MARKER):
                if check:
                    differences.append(str(file.relative_to(root)) + ' (stale)')
                else:
                    file.unlink()
    save(catalogue_path / 'classes.json', json.dumps(classes, ensure_ascii=False, indent=2) + '\n')
    save(catalogue_path / 'generated-files.json', json.dumps(files, indent=2) + '\n')
    if differences:
        print('\n'.join(differences[:30]))
        raise SystemExit(f'{len(differences)} generated files differ; rerun without --check.')
    print(f'Generated {len(classes)} dictionary classes, {len(classes)} immutable definitions and {len(files) - 2 * len(classes)} entry classes.')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument('--check', action='store_true')
    arguments = parser.parse_args()
    generate(arguments.root, arguments.check)
