#!/usr/bin/env python3
"""Generate only the explicitly reviewed ISO 32000-2:2020 EC3 pilot schemas.

The authored pilot catalogue does not reproduce the supplied private source PDF
or imply that the remaining dictionary tables and PDF 2.0 mechanisms are covered.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from generate_specification import nullable_string, php_bool, php_string, value_classes

MARKER = '// Generated by tools/generate_iso32000_2_pilot.py; edit the reviewed pilot catalogue.'
HEADER = '<?php\n\n' + MARKER + '\n\ndeclare(strict_types=1);\n\n'
NAMESPACE = 'PDF\\Specification\\Iso32000_2'


def generate(root: Path, check: bool = False) -> None:
    catalogue = root / 'resources' / 'iso32000-2-2020'
    metadata = json.loads((catalogue / 'metadata.json').read_text(encoding='utf-8'))
    tables = json.loads((catalogue / 'dictionaries.json').read_text(encoding='utf-8'))
    files = []
    differences = []
    classes = []

    def save(path: Path, content: str) -> None:
        expected = content.encode('utf-8')
        if check:
            if not path.is_file() or path.read_bytes() != expected:
                differences.append(str(path.relative_to(root)))
        elif not path.is_file() or path.read_bytes() != expected:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(expected)

    def source(table: dict, page: int) -> str:
        edition = 'new SourceEdition(' + ', '.join([
            php_string(metadata['edition_identifier']), php_string(metadata['standard']),
            php_string(metadata['specified_pdf_version']), php_string(metadata['family']),
            'new ErrataCollection(' + str(metadata['errata_collection']['number']) + ', ' + php_string(metadata['errata_collection']['publication_date']) + ')',
        ]) + ')'
        original = metadata['source']
        return 'new SourceReference(' + ', '.join([
            php_string(table['id']), php_string(table['section']), str(page),
            php_string(metadata['standard']), php_string(original['sha256']),
            php_string(original['document']), edition,
        ]) + ')'

    for table in tables:
        name = table['name']
        definition_name = name + 'Definition'
        definition = HEADER + 'namespace ' + NAMESPACE + '\\Definition;\n\n'
        definition += '\n'.join('use PDF\\Specification\\' + item + ';' for item in ['EntryDefinition', 'ErrataCollection', 'ErrataResolution', 'ErrataReviewStatus', 'ObjectTypeConstraint', 'Requirement', 'SourceEdition', 'SourceReference', 'TableDefinition']) + '\n\n'
        definition += '/** Reviewed ISO 32000-2:2020 EC3 pilot, table ' + table['id'] + '. */\n'
        definition += 'final readonly class ' + definition_name + ' extends TableDefinition\n{\n    public function __construct()\n    {\n        parent::__construct(\n            ' + source(table, table['pdf_pages'][0]) + ',\n            ' + php_string(table['title']) + ',\n            [\n'
        generated_entries = []
        for entry in table['entries']:
            requirement = ('Required' if entry['required'] else 'Optional') + ('; conditional' if entry['conditional'] else '')
            if entry['deprecated_in']:
                requirement += '; deprecated in PDF ' + entry['deprecated_in']
            constraint = 'new ObjectTypeConstraint(' + ', '.join([
                php_string(entry['type']), 'indirect: ' + php_bool(entry['indirect']),
                'direct: ' + php_bool(entry['direct']), 'fixedName: ' + nullable_string(entry['fixed_name']),
            ])
            if entry.get('array_member_type'):
                constraint += ', arrayElementConstraint: new ObjectTypeConstraint(' + php_string(entry['array_member_type']) + ')'
            constraint += ')'
            arguments = [php_string(entry['name']), constraint,
                'new Requirement(' + ', '.join([php_string(requirement), php_bool(entry['required']), php_bool(entry['conditional']), 'false', nullable_string(entry['introduced_in'])]) + ')',
                source(table, entry['pdf_page']), php_string(entry['description'])]
            if entry['errata']:
                errata = entry['errata']
                arguments += ['errata: new ErrataResolution(' + ', '.join([
                    php_string(errata['id']), str(errata['pdf_page']), 'ErrataReviewStatus::' + errata['review_status'],
                    'issueNumber: ' + ('null' if errata['issue_number'] is None else str(errata['issue_number'])),
                    'annotationName: ' + nullable_string(errata['annotation_name']),
                ]) + ')']
            definition += '                new EntryDefinition(' + ', '.join(arguments) + '),\n'
            entry_name = entry['name'] + 'Entry'
            types = value_classes(entry)
            entry_php = HEADER + 'namespace ' + NAMESPACE + '\\Dictionary\\' + name + ';\n\nuse ' + NAMESPACE + '\\Definition\\' + definition_name + ';\n'
            for item in sorted(set(types)):
                entry_php += 'use PDF\\Syntax\\' + ('FileStructure' if item == 'BasicType' else 'Object') + '\\' + item + ';\n'
            entry_php += '\n/** ISO 32000-2:2020 EC3, table ' + table['id'] + ', /' + entry['name'] + '. */\nfinal class ' + entry_name + ' extends \\PDF\\Specification\\SchemaEntry\n{\n    public const string TABLE = ' + php_string(table['id']) + ';\n    public const string KEY = ' + php_string(entry['name']) + ';\n\n    public function __construct(' + '|'.join(types) + ' $value)\n    {\n        parent::__construct((new ' + definition_name + '())->entry(' + php_string(entry['name']) + '), $value);\n    }\n}\n'
            path = root / 'src' / 'Specification' / 'Iso32000_2' / 'Dictionary' / name / (entry_name + '.php')
            save(path, entry_php)
            files.append(path.relative_to(root).as_posix())
            generated_entries.append({'name': entry['name'], 'class': NAMESPACE + '\\Dictionary\\' + name + '\\' + entry_name})
        definition += '            ],\n        );\n    }\n}\n'
        path = root / 'src' / 'Specification' / 'Iso32000_2' / 'Definition' / (definition_name + '.php')
        save(path, definition)
        files.append(path.relative_to(root).as_posix())
        dictionary = HEADER + 'namespace ' + NAMESPACE + '\\Dictionary;\n\nuse ' + NAMESPACE + '\\Definition\\' + definition_name + ';\nuse PDF\\Specification\\SchemaDictionary;\nuse PDF\\Syntax\\Object\\DictionaryObject\\Entry;\n\n/** ISO 32000-2:2020 EC3, table ' + table['id'] + '. */\nfinal class ' + name + ' extends SchemaDictionary\n{\n    public const string TABLE = ' + php_string(table['id']) + ';\n\n    public function __construct(Entry ...$entries)\n    {\n        parent::__construct(new ' + definition_name + '(), ...$entries);\n    }\n}\n'
        path = root / 'src' / 'Specification' / 'Iso32000_2' / 'Dictionary' / (name + '.php')
        save(path, dictionary)
        files.append(path.relative_to(root).as_posix())
        classes.append({'table': table['id'], 'class': NAMESPACE + '\\Dictionary\\' + name, 'definition_class': NAMESPACE + '\\Definition\\' + definition_name, 'entries': generated_entries})
    wanted = {(root / file).resolve() for file in files}
    for path in (root / 'src' / 'Specification' / 'Iso32000_2').rglob('*.php'):
        if path.resolve() not in wanted and path.read_text(encoding='utf-8').startswith('<?php\n\n' + MARKER):
            # Check-only stale reporting: no source file deletion by this pilot.
            differences.append(str(path.relative_to(root)) + ' (stale generated file)')
    save(catalogue / 'classes.json', json.dumps(classes, ensure_ascii=False, indent=2) + '\n')
    save(catalogue / 'generated-files.json', json.dumps(files, indent=2) + '\n')
    if differences:
        raise SystemExit('\n'.join(differences))
    print(f'ISO 32000-2 EC3 pilot: {len(tables)} dictionary definitions, {sum(len(t["entries"]) for t in tables)} entries, {len(files)} reproducible PHP files.')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generate(args.root, args.check)
