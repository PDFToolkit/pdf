#!/usr/bin/env python3
"""Reproduce the Unicode 3.2 data used by RFC 4013; no host Unicode version leaks in.

Python's documented stringprep tables and unicodedata.ucd_3_2_0 are the sources.
The generated JSON is shipped with the library; Python is a maintainer tool only.
"""
import argparse
import json
from pathlib import Path
import stringprep
import unicodedata


def ranges(predicate):
    result = []
    start = end = None
    for point in range(0x110000):
        if predicate(chr(point)):
            if start is None:
                start = point
            end = point
        elif start is not None:
            result.append([start, end])
            start = end = None
    if start is not None:
        result.append([start, end])
    return result


def build():
    ucd = unicodedata.ucd_3_2_0
    decomposition = {}
    combining = {}
    composition = {}
    for point in range(0x110000):
        character = chr(point)
        raw = ucd.decomposition(character)
        if raw:
            parts = raw.split()
            compatible = parts[0].startswith("<")
            if compatible:
                parts = parts[1:]
            values = [int(part, 16) for part in parts]
            # normalize() respects the five pre-4.0 normalization corrections;
            # decomposition() alone can expose the corrected modern mapping.
            decomposition[str(point)] = [ord(part) for part in ucd.normalize("NFKD", character)]
            if not compatible and len(values) == 2 and ucd.normalize("NFC", "".join(map(chr, values))) == character:
                composition[f"{values[0]}:{values[1]}"] = point
        rank = ucd.combining(character)
        if rank:
            combining[str(point)] = rank
    prohibited = [stringprep.in_table_c12, stringprep.in_table_c21, stringprep.in_table_c22,
                  stringprep.in_table_c3, stringprep.in_table_c4, stringprep.in_table_c5,
                  stringprep.in_table_c6, stringprep.in_table_c7, stringprep.in_table_c8,
                  stringprep.in_table_c9]
    return dict(unicodeVersion="3.2.0", profile="RFC 4013 / RFC 3454", decomposition=decomposition,
                combining=combining, composition=composition,
                mappedToNothing=ranges(stringprep.in_table_b1),
                nonAsciiSpace=ranges(stringprep.in_table_c12),
                unassigned=ranges(stringprep.in_table_a1),
                prohibited=ranges(lambda char: any(test(char) for test in prohibited)),
                randAL=ranges(stringprep.in_table_d1), leftToRight=ranges(stringprep.in_table_d2))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    data = build()
    destination = root / "resources/security-unicode32/unicode-3.2-saslprep.json"
    content = json.dumps(data, ensure_ascii=True, separators=(",", ":"), sort_keys=True) + "\n"
    php_destination = root / "src/Security/Unicode32SaslprepData.php"
    lines = ["<?php", "", "declare(strict_types=1);", "", "namespace PDF\\Security;", "",
             "/** Frozen Unicode 3.2.0 data; generated by tools/build_saslprep_tables.py. */",
             "final readonly class Unicode32SaslprepData", "{"]
    for name, annotation in [("decomposition", "array<int, list<int>>"), ("combining", "array<int, int>"),
                             ("composition", "array<string, int>"), ("ranges", "array<string, list<array{int, int}>>")]:
        lines += [f"    /** @var {annotation} */", f"    public array ${name};"]
    lines += ["", "    public function __construct()", "    {"]
    for name in ["decomposition", "combining", "composition"]:
        lines.append(f"        $this->{name} = [")
        for key, value in data[name].items():
            php_key = f"'{key}'" if name == "composition" else f"0x{int(key):x}"
            php_value = "[" + ", ".join(f"0x{point:x}" for point in value) + "]" if isinstance(value, list) else str(value)
            lines.append(f"            {php_key} => {php_value},")
        lines += ["        ];"]
    lines += ["        $this->ranges = ["]
    for name in ["mappedToNothing", "nonAsciiSpace", "unassigned", "prohibited", "randAL", "leftToRight"]:
        lines.append(f"            '{name}' => [")
        lines += [f"                [0x{first:x}, 0x{last:x}]," for first, last in data[name]]
        lines += ["            ],"]
    lines += ["        ];", "    }", "}", ""]
    php_content = "\n".join(lines)
    if args.check:
        if destination.read_text(encoding="utf-8") != content or php_destination.read_text(encoding="utf-8") != php_content:
            raise SystemExit("The shipped Unicode 3.2 SASLprep data differs from the reproducible source tables.")
        print("Unicode 3.2 SASLprep tables reproduce exactly.")
    else:
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(content, encoding="utf-8", newline="\n")
        php_destination.write_text(php_content, encoding="utf-8", newline="\n")
        print(destination)


if __name__ == "__main__":
    main()
