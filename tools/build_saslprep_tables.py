#!/usr/bin/env python3
"""Reproduce the Unicode 3.2 data used by RFC 4013; no host Unicode version leaks in.

Retained RFC 3454 character ranges and unicodedata.ucd_3_2_0 are the sources.
No host stringprep classification is used. Python is a maintainer tool only.
"""
import argparse
import json
from pathlib import Path
import re
import unicodedata


def compact_ranges(parts):
    merged = []
    for first, last in sorted(parts):
        if merged and first <= merged[-1][1] + 1:
            merged[-1][1] = max(last, merged[-1][1])
        else:
            merged.append([first, last])
    return merged


def rfc_tables():
    """Read normative ranges as data, independent of Python's stringprep fixes."""
    source = Path(__file__).resolve().parents[1] / "resources/security-unicode32/rfc3454.txt"
    tables = {}
    name = None
    for line in source.read_text(encoding="utf-8").splitlines():
        start = re.fullmatch(r"\s*----- Start Table ([A-D](?:\.\d+)+) -----\s*", line)
        if start:
            name = start[1]
            tables[name] = []
            continue
        end = re.fullmatch(r"\s*----- End Table ([A-D](?:\.\d+)+) -----\s*", line)
        if end:
            if name != end[1]:
                raise ValueError("Inconsistent RFC character table boundary.")
            name = None
            continue
        row = re.match(r"^\s*([0-9A-F]{4,6})(?:-([0-9A-F]{4,6}))?(?=;|\s*$)", line)
        if name is not None and row:
            first = int(row[1], 16)
            last = int(row[2], 16) if row[2] else first
            if first > last or last > 0x10ffff:
                raise ValueError("Invalid RFC character table range.")
            tables[name].append([first, last])
    required = ["A.1", "B.1", "C.1.2", "C.2.1", "C.2.2", "C.3", "C.4", "C.5", "C.6", "C.7", "C.8", "C.9", "D.1", "D.2"]
    if name is not None or any(not tables.get(key) for key in required):
        raise ValueError("The retained RFC is missing a required SASLprep character table.")
    return {key: compact_ranges(tables[key]) for key in required}


def build():
    ucd = unicodedata.ucd_3_2_0
    decomposition = {}
    combining = {}
    composition = {}
    for point in range(0x110000):
        character = chr(point)
        # Newer Python patch releases expose algorithmic Hangul decompositions
        # here; older releases returned ''. PHP implements these syllables
        # algorithmically, so never duplicate them in the generated data.
        raw = "" if 0xac00 <= point <= 0xd7a3 else ucd.decomposition(character)
        if raw:
            parts = raw.split()
            compatible = parts[0].startswith("<")
            if compatible:
                parts = parts[1:]
            values = [int(part, 16) for part in parts]
            # normalize() respects the five pre-4.0 normalization corrections;
            # decomposition() alone can expose the corrected modern mapping.
            decomposition[str(point)] = [ord(part) for part in ucd.normalize("NFKD", character)]
            if not compatible and len(values) == 2 and ucd.normalize("NFC", "".join(map(chr, values))) == character:
                composition[f"{values[0]}:{values[1]}"] = point
        rank = ucd.combining(character)
        if rank:
            combining[str(point)] = rank
    tables = rfc_tables()
    prohibited = compact_ranges([part for name, parts in tables.items() if name.startswith("C.") for part in parts])
    return dict(unicodeVersion="3.2.0", profile="RFC 4013 / RFC 3454", decomposition=decomposition,
                combining=combining, composition=composition,
                mappedToNothing=tables["B.1"],
                nonAsciiSpace=tables["C.1.2"],
                unassigned=tables["A.1"],
                prohibited=prohibited,
                randAL=tables["D.1"], leftToRight=tables["D.2"])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    data = build()
    destination = root / "resources/security-unicode32/unicode-3.2-saslprep.json"
    content = json.dumps(data, ensure_ascii=True, separators=(",", ":"), sort_keys=True) + "\n"
    php_destination = root / "src/Security/Unicode32SaslprepData.php"
    lines = ["<?php", "", "declare(strict_types=1);", "", "namespace PDF\\Security;", "",
             "/** Frozen Unicode 3.2.0 data; generated by tools/build_saslprep_tables.py. */",
             "final readonly class Unicode32SaslprepData", "{"]
    for name, annotation in [("decomposition", "array<int, list<int>>"), ("combining", "array<int, int>"),
                             ("composition", "array<string, int>"), ("ranges", "array<string, list<array{int, int}>>")]:
        lines += [f"    /** @var {annotation} */", f"    public array ${name};"]
    lines += ["", "    public function __construct()", "    {"]
    for name in ["decomposition", "combining", "composition"]:
        lines.append(f"        $this->{name} = [")
        for key, value in data[name].items():
            php_key = f"'{key}'" if name == "composition" else f"0x{int(key):x}"
            php_value = "[" + ", ".join(f"0x{point:x}" for point in value) + "]" if isinstance(value, list) else str(value)
            lines.append(f"            {php_key} => {php_value},")
        lines += ["        ];"]
    lines += ["        $this->ranges = ["]
    for name in ["mappedToNothing", "nonAsciiSpace", "unassigned", "prohibited", "randAL", "leftToRight"]:
        lines.append(f"            '{name}' => [")
        lines += [f"                [0x{first:x}, 0x{last:x}]," for first, last in data[name]]
        lines += ["            ],"]
    lines += ["        ];", "    }", "}", ""]
    php_content = "\n".join(lines)
    if args.check:
        if destination.read_text(encoding="utf-8") != content or php_destination.read_text(encoding="utf-8") != php_content:
            raise SystemExit("The shipped Unicode 3.2 SASLprep data differs from the reproducible source tables.")
        print("Unicode 3.2 SASLprep tables reproduce exactly.")
    else:
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(content, encoding="utf-8", newline="\n")
        php_destination.write_text(php_content, encoding="utf-8", newline="\n")
        print(destination)


if __name__ == "__main__":
    main()
